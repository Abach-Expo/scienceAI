                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-text-muted hover:text-text-primary hover:bg-bg-tertiary transition-colors text-sm"
              >
                <ChevronLeft size={18} />
                {t('academicWorks.back')}
